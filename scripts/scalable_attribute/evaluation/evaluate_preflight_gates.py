#!/usr/bin/env python3
"""Plan affected-branch decisions from a preflight check manifest.

The input is a JSON *list* of checks.  A check has the following shape::

    {
      "check_id": "metric_contract",
      "scope_kind": "global",
      "scope": "scientific_contract",
      "status": "PASS",
      "evidence": "recorded in run contract"
    }

``scope`` is a string for dataset, loader, and operating-point checks.  A
branch scope is an object with ``dataset``, ``method``, ``operating_point``,
and, for Ours, ``loader_family``.  ``scope_value`` and ``scope_values`` are
accepted as spelling-compatible aliases for ``scope`` so manifests can be
generated by small shell or JSON tools without a translation step.  Values
are still validated against the finite formal evaluation model below.

The model contains 48 branches: for each of three datasets Unicorn has nine
released rate points and Ours has seven frozen operating points.  Ours uses
the loader family selected by its operating point:

* ``standard``: 512, 1K, 8K, and 16K;
* ``rescued_2k``: 2K;
* ``joint_4k``: 4K;
* ``sequential_32k``: 32K.

This module intentionally imports only the Python standard library.  It
validates the complete input before publishing either output.  JSON and TSV
files are written through same-directory temporary files followed by
``os.replace`` so readers never observe a partially written matrix.
"""

from __future__ import annotations

import argparse
import csv
import io
import json
import os
import sys
import tempfile
from pathlib import Path
from typing import Any, Mapping, Sequence


SCHEMA_VERSION = 1

DATASETS = ("8iVFB", "Owlii", "CTC")
METHODS = ("Unicorn", "Ours")
UNICORN_OPERATING_POINTS = (
    "32k", "16k", "8k", "4k", "2k", "1k", "512", "256", "128",
)
OURS_OPERATING_POINTS = ("32k", "16k", "8k", "4k", "2k", "1k", "512")
OPERATING_POINTS = UNICORN_OPERATING_POINTS
POINTS = OPERATING_POINTS
OURS_LOADER_FAMILIES = (
    "standard",
    "rescued_2k",
    "joint_4k",
    "sequential_32k",
)
LOADER_FAMILIES = OURS_LOADER_FAMILIES
POINT_TO_LOADER = {
    "512": "standard",
    "1k": "standard",
    "2k": "rescued_2k",
    "4k": "joint_4k",
    "8k": "standard",
    "16k": "standard",
    "32k": "sequential_32k",
}
SCOPE_KINDS = (
    "global",
    "dataset",
    "loader",
    "operating_point",
    "branch",
)

_CHECK_FIELDS = frozenset(
    {"check_id", "scope_kind", "scope", "status", "evidence"}
)
_SCOPE_FIELD_ALIASES = ("scope", "scope_value", "scope_values")
_STATUS_VALUES = frozenset(("PASS", "FAIL"))


class PreflightGateError(ValueError):
    """Base class for malformed or contradictory preflight input."""


class PreflightSchemaError(PreflightGateError):
    """Raised when a check manifest does not satisfy the input schema."""


class DuplicateCheckError(PreflightSchemaError):
    """Raised when a check identifier occurs more than once."""


# Short aliases keep the public error surface convenient for callers that use
# the script as a small library.
GateError = PreflightGateError
SchemaError = PreflightSchemaError


def _schema_error(message: str) -> PreflightSchemaError:
    return PreflightSchemaError(message)


def _require_nonempty_string(value: Any, label: str) -> str:
    if not isinstance(value, str) or not value or value.strip() != value:
        raise _schema_error(f"{label} must be a non-empty string")
    return value


def _require_evidence(value: Any, label: str) -> Any:
    if isinstance(value, str):
        if not value or not value.strip():
            raise _schema_error(f"{label} must not be empty")
        return value
    if isinstance(value, (Mapping, list)):
        if not value:
            raise _schema_error(f"{label} must not be empty")
        return value
    raise _schema_error(f"{label} must be a non-empty string, object, or list")


def _canonical_dataset(value: Any, label: str) -> str:
    value = _require_nonempty_string(value, label)
    if value not in DATASETS:
        raise _schema_error(
            f"{label} must be one of {', '.join(DATASETS)}; got {value!r}"
        )
    return value


def _canonical_method(value: Any, label: str) -> str:
    value = _require_nonempty_string(value, label)
    if value not in METHODS:
        raise _schema_error(
            f"{label} must be one of {', '.join(METHODS)}; got {value!r}"
        )
    return value


def _canonical_loader(value: Any, label: str) -> str:
    value = _require_nonempty_string(value, label)
    normalized = value.lower().replace("-", "_")
    if normalized not in OURS_LOADER_FAMILIES:
        raise _schema_error(
            f"{label} must be one of {', '.join(OURS_LOADER_FAMILIES)}; "
            f"got {value!r}"
        )
    return normalized


def _canonical_point(value: Any, label: str) -> str:
    if isinstance(value, bool):
        raise _schema_error(f"{label} must be an operating-point value")
    if isinstance(value, int):
        value = str(value)
    value = _require_nonempty_string(value, label)
    normalized = value.lower()
    aliases = {
        "512": "512",
        "1024": "1k",
        "1k": "1k",
        "2048": "2k",
        "2k": "2k",
        "4096": "4k",
        "4k": "4k",
        "8192": "8k",
        "8k": "8k",
        "16384": "16k",
        "16k": "16k",
        "32768": "32k",
        "32k": "32k",
        "256": "256",
        "128": "128",
    }
    if normalized not in aliases:
        raise _schema_error(
            f"{label} must be one of {', '.join(OPERATING_POINTS)}; "
            f"got {value!r}"
        )
    return aliases[normalized]


def _json_object_no_duplicates(pairs: list[tuple[str, Any]]) -> dict[str, Any]:
    result: dict[str, Any] = {}
    for key, value in pairs:
        if key in result:
            raise ValueError(f"duplicate JSON object key {key!r}")
        result[key] = value
    return result


def _load_json(path: Path) -> Any:
    try:
        text = path.read_text(encoding="utf-8")
    except OSError as exc:
        raise PreflightGateError(f"cannot read checks JSON {path}: {exc}") from exc
    try:
        return json.loads(text, object_pairs_hook=_json_object_no_duplicates)
    except (UnicodeDecodeError, json.JSONDecodeError, ValueError) as exc:
        raise PreflightGateError(f"invalid checks JSON {path}: {exc}") from exc


def load_checks(path: os.PathLike[str] | str) -> list[dict[str, Any]]:
    """Load and schema-validate the required top-level JSON list."""

    payload = _load_json(Path(path))
    if not isinstance(payload, list):
        raise PreflightSchemaError("checks JSON root must be a list")
    return validate_checks(payload)


def _scope_key_and_value(raw: Any, labels: tuple[str, ...], label: str) -> Any:
    """Extract one explicitly named value from a scope object."""

    if not isinstance(raw, Mapping):
        return raw
    present = [key for key in labels if key in raw]
    unknown = [key for key in raw if key not in labels]
    if unknown:
        raise _schema_error(
            f"{label} has unexpected field(s): {', '.join(map(str, unknown))}"
        )
    if len(present) != 1:
        raise _schema_error(
            f"{label} must contain exactly one of {', '.join(labels)}"
        )
    return raw[present[0]]


def _canonical_values(
    raw: Any,
    *,
    labels: tuple[str, ...],
    label: str,
    canonicalizer,
) -> tuple[str, ...]:
    raw = _scope_key_and_value(raw, labels, label)
    if isinstance(raw, list):
        if not raw:
            raise _schema_error(f"{label} must contain at least one value")
        values = tuple(canonicalizer(value, f"{label}[{index}]")
                       for index, value in enumerate(raw))
    else:
        values = (canonicalizer(raw, label),)
    if len(set(values)) != len(values):
        raise _schema_error(f"{label} contains duplicate values")
    return values


def _branch_id(
    dataset: str,
    method: str,
    operating_point: str,
    loader_family: str | None,
) -> str:
    if method == "Ours":
        assert loader_family is not None
        return "/".join((dataset, method, loader_family, operating_point))
    return "/".join((dataset, method, operating_point))


def build_branches() -> list[dict[str, Any]]:
    """Return fresh dictionaries for every modeled evaluation branch."""

    branches: list[dict[str, Any]] = []
    for dataset in DATASETS:
        for method in METHODS:
            points = (UNICORN_OPERATING_POINTS
                      if method == "Unicorn" else OURS_OPERATING_POINTS)
            for operating_point in points:
                loader_family = (
                    POINT_TO_LOADER[operating_point] if method == "Ours" else None
                )
                branches.append(
                    {
                        "branch_id": _branch_id(
                            dataset, method, operating_point, loader_family
                        ),
                        "dataset": dataset,
                        "method": method,
                        "loader_family": loader_family,
                        "operating_point": operating_point,
                    }
                )
    return branches


BRANCHES = tuple(build_branches())


def _branch_by_id(branch_id: str) -> dict[str, Any] | None:
    """Resolve canonical and common delimiter/order spellings of a branch ID."""

    branch_map = {branch["branch_id"]: branch for branch in BRANCHES}
    for branch in BRANCHES:
        dataset = branch["dataset"]
        method = branch["method"]
        point = branch["operating_point"]
        loader = branch["loader_family"]
        aliases = {
            branch["branch_id"],
            branch["branch_id"].replace("/", ":"),
            branch["branch_id"].replace("/", "|"),
        }
        if method == "Unicorn":
            aliases.update(
                {
                    f"{dataset}/{method}/{point}",
                    f"{dataset}:{method}:{point}",
                }
            )
        else:
            assert loader is not None
            aliases.update(
                {
                    f"{dataset}/{method}/{point}/{loader}",
                    f"{dataset}:{method}:{point}:{loader}",
                }
            )
        if branch_id in aliases:
            return dict(branch)
    # Keep the local variable useful to type checkers and make the intended
    # exact-match path obvious to readers.
    return branch_map.get(branch_id)


def _normalize_branch_mapping(raw: Mapping[str, Any], label: str) -> dict[str, Any]:
    allowed = {
        "branch_id",
        "dataset",
        "method",
        "loader",
        "loader_family",
        "point",
        "operating_point",
    }
    unknown = [key for key in raw if key not in allowed]
    if unknown:
        raise _schema_error(
            f"{label} has unexpected field(s): {', '.join(map(str, unknown))}"
        )

    branch_from_id: dict[str, Any] | None = None
    if "branch_id" in raw:
        branch_id = _require_nonempty_string(raw["branch_id"], f"{label}.branch_id")
        branch_from_id = _branch_by_id(branch_id)
        if branch_from_id is None:
            raise _schema_error(f"{label}.branch_id is not a modeled branch")

    def _one_of(keys: tuple[str, ...], field: str) -> Any:
        present = [key for key in keys if key in raw]
        if len(present) > 1:
            raise _schema_error(f"{label} may specify only one {field} field")
        return raw[present[0]] if present else None

    raw_dataset = _one_of(("dataset",), "dataset")
    raw_method = _one_of(("method",), "method")
    raw_loader = _one_of(("loader_family", "loader"), "loader family")
    raw_point = _one_of(("operating_point", "point"), "operating point")

    has_dimensions = any(
        value is not None for value in (raw_dataset, raw_method, raw_loader, raw_point)
    )
    if branch_from_id is None and not has_dimensions:
        raise _schema_error(
            f"{label} must contain branch_id or dataset/method/operating_point"
        )

    if branch_from_id is not None:
        expected = branch_from_id
        if raw_dataset is not None and _canonical_dataset(raw_dataset, f"{label}.dataset") != expected["dataset"]:
            raise _schema_error(f"{label} dimensions disagree with branch_id")
        if raw_method is not None and _canonical_method(raw_method, f"{label}.method") != expected["method"]:
            raise _schema_error(f"{label} dimensions disagree with branch_id")
        if raw_loader is not None:
            if expected["loader_family"] is None:
                if raw_loader is not None:
                    raise _schema_error(f"{label} Unicorn branch cannot have a loader")
            elif _canonical_loader(raw_loader, f"{label}.loader_family") != expected["loader_family"]:
                raise _schema_error(f"{label} dimensions disagree with branch_id")
        if raw_point is not None and _canonical_point(raw_point, f"{label}.operating_point") != expected["operating_point"]:
            raise _schema_error(f"{label} dimensions disagree with branch_id")
        return expected

    dataset = _canonical_dataset(raw_dataset, f"{label}.dataset")
    method = _canonical_method(raw_method, f"{label}.method")
    operating_point = _canonical_point(raw_point, f"{label}.operating_point")
    if method == "Ours":
        if operating_point not in OURS_OPERATING_POINTS:
            raise _schema_error(
                f"{label} Ours operating_point must be one of "
                f"{', '.join(OURS_OPERATING_POINTS)}"
            )
        if raw_loader is None:
            raise _schema_error(f"{label} Ours branch must specify loader_family")
        loader_family = _canonical_loader(raw_loader, f"{label}.loader_family")
        expected_loader = POINT_TO_LOADER[operating_point]
        if loader_family != expected_loader:
            raise _schema_error(
                f"{label} loader_family {loader_family!r} does not match "
                f"operating_point {operating_point!r} ({expected_loader!r})"
            )
    else:
        if raw_loader is not None:
            raise _schema_error(f"{label} Unicorn branch cannot have a loader")
        loader_family = None
    branch = {
        "branch_id": _branch_id(dataset, method, operating_point, loader_family),
        "dataset": dataset,
        "method": method,
        "loader_family": loader_family,
        "operating_point": operating_point,
    }
    return branch


def _normalize_branch_scope(raw: Any, label: str) -> tuple[dict[str, Any], ...]:
    if isinstance(raw, list):
        if not raw:
            raise _schema_error(f"{label} must contain at least one branch")
        values = tuple(
            _normalize_branch_mapping(value, f"{label}[{index}]")
            if isinstance(value, Mapping)
            else _normalize_branch_id(value, f"{label}[{index}]")
            for index, value in enumerate(raw)
        )
    elif isinstance(raw, Mapping):
        if "branch" in raw:
            if len(raw) != 1:
                raise _schema_error(f"{label} has unexpected branch fields")
            return _normalize_branch_scope(raw["branch"], label + ".branch")
        values = (_normalize_branch_mapping(raw, label),)
    else:
        values = (_normalize_branch_id(raw, label),)
    ids = [value["branch_id"] for value in values]
    if len(set(ids)) != len(ids):
        raise _schema_error(f"{label} contains duplicate branches")
    return values


def _normalize_branch_id(raw: Any, label: str) -> dict[str, Any]:
    value = _require_nonempty_string(raw, label)
    branch = _branch_by_id(value)
    if branch is None:
        raise _schema_error(f"{label} is not a modeled branch")
    return branch


def _serialize_scope(scope: Any) -> Any:
    if isinstance(scope, tuple):
        return [_serialize_scope(value) for value in scope]
    if isinstance(scope, Mapping):
        return {str(key): _serialize_scope(value) for key, value in scope.items()}
    if isinstance(scope, list):
        return [_serialize_scope(value) for value in scope]
    return scope


def _scope_text(check: Mapping[str, Any]) -> str:
    scope = _serialize_scope(check["scope"])
    if isinstance(scope, str):
        return scope
    return json.dumps(scope, sort_keys=True, ensure_ascii=False)


def _normalize_check(raw: Any, index: int) -> dict[str, Any]:
    label = f"checks[{index}]"
    if not isinstance(raw, Mapping):
        raise _schema_error(f"{label} must be an object")
    unknown = [key for key in raw if key not in _CHECK_FIELDS and key not in {"scope_value", "scope_values"}]
    if unknown:
        raise _schema_error(
            f"{label} has unexpected field(s): {', '.join(map(str, unknown))}"
        )
    missing = [key for key in ("check_id", "scope_kind", "status", "evidence") if key not in raw]
    if missing:
        raise _schema_error(f"{label} missing required field(s): {', '.join(missing)}")
    scope_fields = [key for key in _SCOPE_FIELD_ALIASES if key in raw]
    if len(scope_fields) != 1:
        raise _schema_error(
            f"{label} must contain exactly one of {', '.join(_SCOPE_FIELD_ALIASES)}"
        )

    check_id = _require_nonempty_string(raw["check_id"], f"{label}.check_id")
    scope_kind = _require_nonempty_string(raw["scope_kind"], f"{label}.scope_kind")
    if scope_kind not in SCOPE_KINDS:
        raise _schema_error(
            f"{label}.scope_kind must be one of {', '.join(SCOPE_KINDS)}; "
            f"got {scope_kind!r}"
        )
    status = raw["status"]
    if not isinstance(status, str) or status not in _STATUS_VALUES:
        raise _schema_error(
            f"{label}.status must be PASS or FAIL; got {status!r}"
        )
    evidence = _require_evidence(raw["evidence"], f"{label}.evidence")
    raw_scope = raw[scope_fields[0]]

    if scope_kind == "global":
        if raw_scope is not None and not isinstance(raw_scope, (str, Mapping)):
            raise _schema_error(
                f"{label}.scope must be null, a string, or an object for global checks"
            )
        scope = raw_scope
        scope_values: tuple[Any, ...] = (scope,)
    elif scope_kind == "dataset":
        scope_values = _canonical_values(
            raw_scope,
            labels=("dataset", "datasets", "value", "values"),
            label=f"{label}.scope",
            canonicalizer=_canonical_dataset,
        )
        scope = scope_values[0] if len(scope_values) == 1 else scope_values
    elif scope_kind == "loader":
        scope_values = _canonical_values(
            raw_scope,
            labels=("loader", "loader_family", "loaders", "values", "value"),
            label=f"{label}.scope",
            canonicalizer=_canonical_loader,
        )
        scope = scope_values[0] if len(scope_values) == 1 else scope_values
    elif scope_kind == "operating_point":
        scope_values = _canonical_values(
            raw_scope,
            labels=("operating_point", "point", "operating_points", "points", "values", "value"),
            label=f"{label}.scope",
            canonicalizer=_canonical_point,
        )
        scope = scope_values[0] if len(scope_values) == 1 else scope_values
    else:
        scope_values = _normalize_branch_scope(raw_scope, f"{label}.scope")
        scope = scope_values[0]["branch_id"] if len(scope_values) == 1 else scope_values

    return {
        "check_id": check_id,
        "scope_kind": scope_kind,
        "scope": scope,
        "scope_values": scope_values,
        "status": status,
        "evidence": evidence,
    }


def validate_checks(checks: Sequence[Any]) -> list[dict[str, Any]]:
    """Validate and normalize a non-empty sequence of preflight checks.

    Duplicate check IDs, duplicate JSON object keys, unknown scope values, and
    contradictory Ours loader/point combinations all fail before planning.
    """

    if not isinstance(checks, Sequence) or isinstance(checks, (str, bytes, Mapping)):
        raise PreflightSchemaError("checks must be a JSON list")
    if not checks:
        raise PreflightSchemaError("checks list must not be empty")
    normalized: list[dict[str, Any]] = []
    seen_ids: set[str] = set()
    for index, raw in enumerate(checks):
        check = _normalize_check(raw, index)
        check_id = check["check_id"]
        if check_id in seen_ids:
            raise DuplicateCheckError(f"duplicate check_id {check_id!r}")
        seen_ids.add(check_id)
        normalized.append(check)
    return normalized


def _matches(branch: Mapping[str, Any], check: Mapping[str, Any]) -> bool:
    scope_kind = check["scope_kind"]
    values = check["scope_values"]
    if scope_kind == "global":
        return True
    if scope_kind == "dataset":
        return branch["dataset"] in values
    if scope_kind == "loader":
        return (
            branch["method"] == "Ours"
            and branch["loader_family"] in values
        )
    if scope_kind == "operating_point":
        return branch["operating_point"] in values
    return any(value["branch_id"] == branch["branch_id"] for value in values)


def _evidence_text(value: Any) -> str:
    if isinstance(value, str):
        return value
    return json.dumps(value, sort_keys=True, ensure_ascii=False)


def _serialize_check(check: Mapping[str, Any]) -> dict[str, Any]:
    return {
        "check_id": check["check_id"],
        "scope_kind": check["scope_kind"],
        "scope": _serialize_scope(check["scope"]),
        "status": check["status"],
        "evidence": check["evidence"],
    }


def _plan_validated(normalized: Sequence[Mapping[str, Any]]) -> dict[str, Any]:
    """Build a matrix from checks already validated by ``validate_checks``.

    A failed global check is a scientific-contract failure and changes every
    branch to ``HOLD_ALL``.  In the absence of a failed global check, only
    branches matching a failed local check become ``HOLD``.
    """

    failed = [check for check in normalized if check["status"] == "FAIL"]
    global_failures = [check for check in failed if check["scope_kind"] == "global"]
    branches: list[dict[str, Any]] = []

    for model_branch in BRANCHES:
        matched = (
            global_failures
            if global_failures
            else [check for check in failed if _matches(model_branch, check)]
        )
        if global_failures:
            decision = "HOLD_ALL"
        elif matched:
            decision = "HOLD"
        else:
            decision = "ELIGIBLE"

        reasons: list[str] = []
        evidence: list[dict[str, Any]] = []
        for check in matched:
            if check["scope_kind"] == "global":
                reason = f"{check['check_id']}: global scientific-contract failure"
            else:
                reason = (
                    f"{check['check_id']}: {check['scope_kind']} scope "
                    f"{_scope_text(check)} failed"
                )
            reason += f"; evidence: {_evidence_text(check['evidence'])}"
            reasons.append(reason)
            evidence.append(_serialize_check(check))

        branches.append(
            {
                **model_branch,
                "decision": decision,
                "failed_check_ids": [check["check_id"] for check in matched],
                "reasons": reasons,
                "evidence": evidence,
            }
        )

    counts = {
        "total_checks": len(normalized),
        "passed_checks": sum(check["status"] == "PASS" for check in normalized),
        "failed_checks": len(failed),
        "global_failed_checks": len(global_failures),
        "total_branches": len(branches),
        "eligible": sum(row["decision"] == "ELIGIBLE" for row in branches),
        "hold": sum(row["decision"] == "HOLD" for row in branches),
        "hold_all": sum(row["decision"] == "HOLD_ALL" for row in branches),
    }
    counts["held"] = counts["hold"] + counts["hold_all"]
    if global_failures:
        status = "HOLD_ALL"
    elif counts["hold"]:
        status = "HOLD"
    else:
        status = "ELIGIBLE"

    return {
        "schema_version": SCHEMA_VERSION,
        "status": status,
        "model": {
            "datasets": list(DATASETS),
            "methods": list(METHODS),
            "ours_loader_families": list(OURS_LOADER_FAMILIES),
            "unicorn_operating_points": list(UNICORN_OPERATING_POINTS),
            "ours_operating_points": list(OURS_OPERATING_POINTS),
            "branch_count": len(BRANCHES),
        },
        "counts": counts,
        "checks": [_serialize_check(check) for check in normalized],
        "failed_checks": [_serialize_check(check) for check in failed],
        "global_failures": [_serialize_check(check) for check in global_failures],
        "branches": branches,
    }


def plan_preflight_gates(checks: Sequence[Any]) -> dict[str, Any]:
    """Return the complete affected-branch decision matrix."""

    return _plan_validated(validate_checks(checks))


def evaluate_preflight_gates(checks: Sequence[Any]) -> dict[str, Any]:
    """Compatibility-facing name for :func:`plan_preflight_gates`."""

    return plan_preflight_gates(checks)


def build_decision_matrix(checks: Sequence[Any]) -> dict[str, Any]:
    """Compatibility-facing name for :func:`plan_preflight_gates`."""

    return plan_preflight_gates(checks)


